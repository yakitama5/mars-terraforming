"""Bundle the already-built Flutter web app with an offline cache, no CDN."""
from hashlib import sha256
import json
from pathlib import Path
import shutil

root = Path(__file__).resolve().parent.parent
source = root / 'build/web'
if not (source / 'index.html').is_file():
    raise SystemExit('Run flutter build web first.')
files = sorted(p for p in source.rglob('*') if p.is_file()
               and not any(part.startswith('.') for part in p.relative_to(source).parts)
               and p.name not in ('offline_worker.js', 'flutter_service_worker.js'))
digest = sha256()
for path in files:
    digest.update(path.relative_to(source).as_posix().encode())
    digest.update(path.read_bytes())
resources = json.dumps([p.relative_to(source).as_posix() for p in files])
worker = '''// Generated by tools/prepare_web_preview.py. Only caches this game.
const FILES = RESOURCES;
const base = new URL('./', self.location.href);
// CacheStorage is origin-wide, even for distinct service-worker scopes.
const PREFIX = 'mars-terraforming:' + encodeURIComponent(base.pathname) + ':';
const CACHE = PREFIX + 'VERSION';
const urls = FILES.map(file => new URL(file, base).href);
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(urls)));
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== base.origin) return;
  if (event.request.mode === 'navigate' && url.pathname === base.pathname) {
    event.respondWith(fetch(event.request).catch(() =>
      caches.open(CACHE).then(cache => cache.match(new URL('index.html', base).href))));
    return;
  }
  url.search = '';
  if (!urls.includes(url.href)) return;
  event.respondWith(caches.open(CACHE).then(async cache =>
    await cache.match(url.href) || fetch(event.request)));
});
'''.replace('VERSION', digest.hexdigest()[:16]).replace('RESOURCES', resources)
(source / 'offline_worker.js').write_text(worker)
destination = root / 'site-preview/dist'
manifest_directory = destination.parent / '.openai'
manifest_directory.mkdir(parents=True, exist_ok=True)
shutil.copyfile(root / 'tools/site_hosting.json', manifest_directory / 'hosting.json')
# Replace only generated output; never touch source or Site identity.
if destination.exists():
    shutil.rmtree(destination)
# GitHub's Pages artifact excludes dotfiles; never precache absent build metadata.
shutil.copytree(source, destination, ignore=shutil.ignore_patterns('.*'))
print(f'Prepared {len(files)} local resources: {destination}')
