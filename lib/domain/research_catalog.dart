/// Playable research knowledge and its first concrete application.
/// Costs, durations and operating values belong to GameContent.
/// Existing save identifiers are retained even when the scientific title changes.
enum ResearchField { bio, mechanics, materials, energy }

extension ResearchFieldDisplay on ResearchField {
  String get label => switch (this) {
    ResearchField.bio => 'バイオ',
    ResearchField.mechanics => 'メカニクス',
    ResearchField.materials => 'マテリアル',
    ResearchField.energy => 'エネルギー',
  };

  String get assetPath => 'assets/images/research/field_$name.png';
}

enum ResearchUnlockKind { facility, vehicle, equipment, process, operation }

enum ResearchUnlockEffect {
  research,
  production,
  transport,
  construction,
  income,
  partnership,
}

extension ResearchUnlockKindDisplay on ResearchUnlockKind {
  String get label => switch (this) {
    ResearchUnlockKind.facility => '施設',
    ResearchUnlockKind.vehicle => '機体',
    ResearchUnlockKind.equipment => '設備',
    ResearchUnlockKind.process => '製法',
    ResearchUnlockKind.operation => '運用',
  };
}

class ResearchTechnology {
  const ResearchTechnology({
    required this.id,
    required this.catalogId,
    required this.name,
    required this.field,
    required this.branch,
    required this.stage,
    required this.description,
    required this.unlockName,
    required this.unlockDescription,
    required this.tradeoff,
    required this.sourceIds,
    required this.unlockKind,
    required this.unlockFacilityId,
    required this.unlockEffect,
    this.prerequisiteIds = const [],
    this.alternativePrerequisiteIds = const [],
    this.integratedIntoId,
  });

  final String id;
  final String catalogId;
  final String name;
  final ResearchField field;
  final String branch;
  final int stage;
  final String description;
  final String unlockName;
  final String unlockDescription;
  final String tradeoff;
  final List<String> sourceIds;
  final List<String> prerequisiteIds;
  final List<String> alternativePrerequisiteIds;
  final ResearchUnlockKind unlockKind;

  /// The shared work queue used to build, fabricate or introduce the unlock.
  final String unlockFacilityId;
  final ResearchUnlockEffect unlockEffect;

  /// Constituent knowledge included in another research, never a second fee.
  final String? integratedIntoId;
  bool get isPurchasable => integratedIntoId == null;

  String get science => [
    for (final id in sourceIds) ResearchCatalog.sources[id]!.explanation,
    'ゲーム上の仮定：施設・機体の形と運営効果は研究を参考にした簡略化です。'
        '研究解放だけで設備や資源を取得したり、火星の屋外居住が成立したりするものではありません。',
  ].join('\n\n');
}

class ResearchSource {
  const ResearchSource({
    required this.id,
    required this.citation,
    required this.title,
    required this.url,
    required this.scope,
    required this.summary,
    required this.limit,
  });
  final String id;
  final String citation;
  final String title;
  final String url;
  final String scope;
  final String summary;
  final String limit;

  String get explanation =>
      '$citation — $title\n確認範囲：$scope\n$summary\n成立条件・限界：$limit\n$url';
}

